import unicodedata
from pathlib import Path

from apidsl import ast

RUNTIME_SOURCE = Path(__file__).with_name("runtime.py").read_text(encoding="utf-8")
INDENT = "    "


def slug(name: str) -> str:
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode("ascii")
    words = "".join(char if char.isalnum() else " " for char in ascii_name.lower()).split()
    return "_".join(words) or "unnamed"


def function_names(names: list[str]) -> list[str]:
    used: set[str] = set()
    result = []
    for name in names:
        base = f"test_{slug(name)}"
        candidate, suffix = base, 2
        while candidate in used:
            candidate, suffix = f"{base}_{suffix}", suffix + 1
        used.add(candidate)
        result.append(candidate)
    return result


def variable(name: str) -> str:
    return f"var_{name}"


def term_code(term: ast.Term) -> str:
    if isinstance(term, ast.VarRef):
        return f"text({variable(term.name)})"
    return ascii(term.value)


def expr_code(expr: ast.Expr) -> str:
    return " + ".join(term_code(part) for part in expr.parts)


def value_code(value: ast.Value) -> str:
    match value:
        case ast.StringLiteral(value=text) | ast.NumberLiteral(value=text) | ast.BoolLiteral(value=text):
            return ascii(text)
        case ast.NullLiteral():
            return "None"
        case ast.VarRef(name=name):
            return variable(name)
        case ast.ObjectLiteral(pairs=pairs):
            return "{" + ", ".join(f"{pair.key!a}: {value_code(pair.value)}" for pair in pairs) + "}"
    raise TypeError(f"unsupported value node {type(value).__name__}")


def request_code(request: ast.Request) -> str:
    args = [
        ascii(request.method.value),
        f"resolve_url(BASE, {expr_code(request.url)})",
        str(request.line),
    ]
    if request.headers:
        headers = ", ".join(f"{header.name!a}: {expr_code(header.value)}" for header in request.headers)
        args.append(f"headers={{{headers}}}")
    if request.body is not None:
        args.append(f"body={value_code(request.body)}")
    return f"response = send({', '.join(args)})"


def statement_code(statement: ast.Statement) -> str:
    match statement:
        case ast.Request():
            return request_code(statement)
        case ast.ExpectStatus(code=code):
            return f"expect_status(response, {code!a}, {statement.line})"
        case ast.ExpectJson(path=path, expected=expected):
            return f"expect_json(response, {path!a}, {value_code(expected)}, {statement.line})"
        case ast.Save(name=name, path=path):
            return f"{variable(name)} = json_path(response, {path!a}, {statement.line})"
    raise TypeError(f"unsupported statement node {type(statement).__name__}")


def function_code(name: str, test: ast.Test) -> list[str]:
    body = [INDENT + statement_code(statement) for statement in test.statements]
    return [f"def {name}():", *(body or [INDENT + "pass"])]


def generate(program: ast.Program, source_name: str) -> str:
    base = ascii(program.base.url) if program.base is not None else "None"
    lines = [
        f"# Generated by apidsl from {Path(source_name).name!a}. Do not edit.",
        "",
        RUNTIME_SOURCE.rstrip(),
        "",
        "",
        f"BASE = {base}",
    ]
    names = function_names([test.name for test in program.tests])
    for name, test in zip(names, program.tests):
        lines += ["", "", *function_code(name, test)]
    return "\n".join(lines) + "\n"
