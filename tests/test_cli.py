from pathlib import Path

import pytest

from apidsl import cli

EXAMPLE = '''BASE "http://localhost:8000";

TEST "Login flow" {
    POST "/login" BODY { "user": "admin", "pass": "123" };
    EXPECT STATUS 200;
}
'''


@pytest.fixture
def example(tmp_path) -> Path:
    path = tmp_path / "login.api"
    path.write_text(EXAMPLE, encoding="utf-8")
    return path


def write(tmp_path: Path, name: str, text: str) -> Path:
    path = tmp_path / name
    path.write_text(text, encoding="utf-8")
    return path


def test_compile_to_file(example, tmp_path, capsys):
    output = tmp_path / "out" / "test_login.py"
    output.parent.mkdir()

    assert cli.main(["compile", str(example), "-o", str(output)]) == 0

    code = output.read_text(encoding="utf-8")
    compile(code, str(output), "exec")
    assert "def test_login_flow():" in code
    assert capsys.readouterr().out == f"compiled {example} -> {output}\n"


def test_compile_to_stdout(example, capsys):
    assert cli.main(["compile", str(example)]) == 0

    out = capsys.readouterr().out
    assert out.startswith("# Generated by apidsl from 'login.api'. Do not edit.\n")
    assert "def test_login_flow():" in out


def test_generated_code_is_ascii_even_for_polish_text(tmp_path, capsys):
    source = write(tmp_path, "pl.api", 'TEST "Zażółć" { GET "http://h/łódź"; }')

    assert cli.main(["compile", str(source)]) == 0

    out = capsys.readouterr().out
    assert out.isascii()
    assert "def test_zazoc():" in out


def test_tokens_flag(example, capsys):
    assert cli.main(["compile", str(example), "--tokens"]) == 0

    lines = capsys.readouterr().out.splitlines()
    assert lines[:3] == [
        "1:1     BASE        BASE",
        '1:6     STRING      "http://localhost:8000"',
        "1:29    SEMI        ;",
    ]
    assert lines[-1] == "7:1     EOF"


def test_ast_flag(example, capsys):
    assert cli.main(["compile", str(example), "--ast"]) == 0

    assert capsys.readouterr().out.splitlines() == [
        "Program @1:1",
        "  base: Base url='http://localhost:8000' @1:1",
        "  tests: Test name='Login flow' @3:1",
        "    statements: Request method=POST @4:5",
        "      url: Expr @4:10",
        "        parts: StringLiteral value='/login' @4:10",
        "      body: ObjectLiteral @4:24",
        "        pairs: Pair key='user' @4:26",
        "          value: StringLiteral value='admin' @4:34",
        "        pairs: Pair key='pass' @4:43",
        "          value: StringLiteral value='123' @4:51",
        "    statements: ExpectStatus code=200 @5:5",
    ]


def test_ast_flag_does_not_run_semantic_checks(tmp_path, capsys):
    source = write(tmp_path, "empty.api", 'TEST "t" { }')

    assert cli.main(["compile", str(source), "--ast"]) == 0
    assert "Test name='t'" in capsys.readouterr().out


def test_tokens_and_ast_are_exclusive(example):
    with pytest.raises(SystemExit) as caught:
        cli.main(["compile", str(example), "--tokens", "--ast"])

    assert caught.value.code == 2


def test_lexical_error(tmp_path, capsys):
    source = write(tmp_path, "bad.api", 'TEST "t" {\n  GET "/x;\n}')

    assert cli.main(["compile", str(source)]) == 1

    captured = capsys.readouterr()
    assert captured.out == ""
    assert captured.err == f"{source}:2:7: LexicalError: unterminated string\n"


def test_lexical_error_with_tokens_flag(tmp_path, capsys):
    source = write(tmp_path, "bad.api", "GET @")

    assert cli.main(["compile", str(source), "--tokens"]) == 1
    assert capsys.readouterr().err == f"{source}:1:5: LexicalError: unexpected character '@'\n"


def test_syntax_error(tmp_path, capsys):
    source = write(tmp_path, "bad.api", 'BASE "http://h"\nTEST "t" { GET "/"; }')

    assert cli.main(["compile", str(source)]) == 1
    assert capsys.readouterr().err == f"{source}:2:1: SyntaxError: expected ';', got 'TEST'\n"


def test_all_semantic_errors_are_reported(tmp_path, capsys):
    source = write(tmp_path, "bad.api", 'TEST "t" {\n  GET "/x" + id;\n  EXPECT STATUS 42;\n}')

    assert cli.main(["compile", str(source)]) == 1
    assert capsys.readouterr().err.splitlines() == [
        f"{source}:2:7: SemanticError: relative path '/x' requires BASE",
        f"{source}:2:14: SemanticError: variable 'id' is used before SAVE",
        f"{source}:3:3: SemanticError: status code 42 is outside 100-599",
    ]


def test_failed_compile_does_not_write_output(tmp_path):
    source = write(tmp_path, "bad.api", 'TEST "t" { }')
    output = tmp_path / "out.py"

    assert cli.main(["compile", str(source), "-o", str(output)]) == 1
    assert not output.exists()


def test_missing_file(tmp_path, capsys):
    missing = tmp_path / "missing.api"

    assert cli.main(["compile", str(missing)]) == 2
    assert capsys.readouterr().err.startswith(f"apidsl: cannot read {missing}: ")


def test_file_with_utf8_bom(tmp_path, capsys):
    source = tmp_path / "bom.api"
    source.write_text('TEST "t" { GET "http://h/"; }', encoding="utf-8-sig")

    assert cli.main(["compile", str(source)]) == 0


def test_run_does_not_start_pytest_when_compilation_fails(tmp_path, monkeypatch, capsys):
    source = write(tmp_path, "bad.api", 'TEST "t" { }')
    monkeypatch.setattr(cli.subprocess, "run", lambda *a, **k: pytest.fail("pytest was started"))

    assert cli.main(["run", str(source)]) == 1
    assert "SemanticError: test 't' is empty" in capsys.readouterr().err
